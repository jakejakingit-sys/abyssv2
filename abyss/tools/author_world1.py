"""Authoring script for World 1. Writes levels/world1/*.txt (after that the .txt files are the source of truth).
Legend: # solid  = one-way  ^ spike  H ladder  $ coin  C chest  E exit  S spawn  x crumble  R rune  G gate
        T torch(decor)  z skull(decor)  k crawler  m moving platform (surface = top of its tile)"""
def mk(W, ops):
    g = [['.'] * W for _ in range(15)]
    for x in range(W): g[0][x] = '#'; g[13][x] = '#'; g[14][x] = '#'
    for y in range(15): g[y][0] = '#'; g[y][W - 1] = '#'
    for ch, x0, x1, y0, y1 in ops:
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1): g[y][x] = ch
    return g
def save(fn, name, W, ops, boss=0):
    g = mk(W, ops)
    hdr = f"name: {name}\nworld: 1\n" + (f"boss: {boss}\n" if boss else "")
    open(f'levels/world1/{fn}.txt', 'w').write(hdr + "\n".join("".join(r) for r in g) + "\n")

