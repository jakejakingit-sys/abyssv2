"""Authoring script for World 2 (Sunken Mines). Writes levels/world2/*.txt. Same legend as author_world1.py."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
def mk(W, ops):
    g = [['.'] * W for _ in range(15)]
    for x in range(W): g[0][x] = '#'; g[13][x] = '#'; g[14][x] = '#'
    for y in range(15): g[y][0] = '#'; g[y][W - 1] = '#'
    for ch, x0, x1, y0, y1 in ops:
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1): g[y][x] = ch
    return g
def save(fn, name, W, ops, boss=0):
    g = mk(W, ops)
    hdr = f"name: {name}\nworld: 2\n" + (f"boss: {boss}\n" if boss else "")
    open(f'levels/world2/{fn}.txt', 'w').write(hdr + "\n".join("".join(r) for r in g) + "\n")

